const {readFileSync} = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const assert = require('node:assert/strict');
const source = readFileSync(path.join(__dirname,'../shell/services/AudioEvents.js'),'utf8').replace(/^\.pragma library\s*/, '');
const events = vm.createContext({});vm.runInContext(source,events);
const state = events.createState();
const endpoint = {id:42,type:'PipeWire:Interface:Node',info:{props:{'media.class':'Audio/Sink','node.name':'speaker ["quoted"]'}}};
const frame = JSON.stringify([endpoint],null,2);
let changed=false;
for(const char of frame) changed=events.feed(state,char)||changed;
assert(changed,'Fragmented JSON array was not recognized');
assert.equal(state.buffer,'');
assert(!events.feed(state,JSON.stringify([{id:90,type:'PipeWire:Interface:Client',info:{props:{'application.name':'pw-dump'}}}])),'Client discovery should not refresh');
assert(!events.feed(state,JSON.stringify([{id:90,info:null}])),'Client removal would cause a query feedback loop');
assert(events.feed(state,JSON.stringify([{id:42,type:'PipeWire:Interface:Node',info:{params:{Props:[{mute:true}]}}}])),'Partial node update was missed');
const metadata={id:2,type:'PipeWire:Interface:Metadata',props:{'metadata.name':'default'},metadata:[{key:'default.audio.source',value:{name:'mic'}}]};
assert(events.feed(state,JSON.stringify([metadata])));
assert(events.feed(state,JSON.stringify([{id:2,type:metadata.type,metadata:[{key:'default.audio.sink',value:{name:'hdmi'}}]}])));
assert(!events.feed(state,JSON.stringify([{id:91,type:'PipeWire:Interface:Node',info:{props:{'media.class':'Stream/Output/Audio'}}}])));
assert(events.feed(state,JSON.stringify([{id:42,info:null}])),'Endpoint removal was missed');
assert(!events.feed(state,JSON.stringify([{id:42,info:null}])),'Repeated removal should be ignored');
assert(events.feed(state,JSON.stringify([endpoint])+JSON.stringify([{id:42,info:null}])),'Concatenated monitor frames failed');
assert.throws(()=>events.feed(events.createState(),'not JSON'));
console.log('PASS: PipeWire event framing, default changes, partial updates, removals and query-loop filtering');
