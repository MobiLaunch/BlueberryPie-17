#!/usr/bin/env python3
"""Generate shell/services/EmojiData.js from the emojibase-data package (MIT, built from Unicode CLDR).

    npm pack emojibase-data@16.0.3 && tar xzf emojibase-data-16.0.3.tgz package/en
    python3 scripts/generate-emoji.py package/en/data.json package/en/messages.json

Skin-tone swatches and hair components (group 2) are left out; skin-tone variants are not listed
separately (the base emoji is). Entries are [emoji, label, tags, group index]."""
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "shell/services/EmojiData.js"
GROUP_TITLES = {"smileys-emotion": "Smileys", "people-body": "People", "animals-nature": "Nature",
                "food-drink": "Food", "travel-places": "Travel", "activities": "Activities",
                "objects": "Objects", "symbols": "Symbols", "flags": "Flags"}


def main(data_path, messages_path):
    data = json.loads(Path(data_path).read_text())
    messages = json.loads(Path(messages_path).read_text())
    keys = [group["key"] for group in sorted(messages["groups"], key=lambda g: g["order"]) if group["key"] in GROUP_TITLES]
    index = {key: position for position, key in enumerate(keys)}
    by_order = {group["order"]: group["key"] for group in messages["groups"]}
    entries = []
    for item in sorted((i for i in data if "group" in i and "order" in i), key=lambda i: i["order"]):
        key = by_order.get(item["group"])
        if key not in index or not item.get("emoji"):
            continue
        entries.append([item["emoji"], item["label"], " ".join(item.get("tags", [])), index[key]])
    body = (".pragma library\n"
            "// Generated by scripts/generate-emoji.py from emojibase-data (MIT; Unicode CLDR names). Do not edit.\n"
            "var groups = " + json.dumps([GROUP_TITLES[key] for key in keys], ensure_ascii=False) + ";\n"
            "var entries = " + json.dumps(entries, ensure_ascii=False, separators=(",", ":")) + ";\n")
    OUT.write_text(body)
    print(f"Wrote {len(entries)} emoji in {len(keys)} groups to {OUT}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
