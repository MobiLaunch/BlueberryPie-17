#!/usr/bin/env python3
"""Generate shared preview tokens and original vector assets; no network."""
import json
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from prismos.theme import PALETTES, legacy_tokens, palette

MATERIAL = ROOT/"design/icons/material"
PATH = re.compile(r'<path d="([^"]+)"/>')


def load_icons():
    """Our icon names -> Material Symbols Rounded path data (outlined and filled).

    The SVGs in design/icons/material are an unmodified subset of
    @material-symbols/svg-400 (Apache-2.0, see design/icons/NOTICE.md); the
    mapping from PrismOS names to symbols is design/icons/material-map.json."""
    mapping = json.loads((ROOT/"design/icons/material-map.json").read_text())
    outline, filled = {}, {}
    for name, symbol in mapping.items():
        for table, suffix in ((outline, ""), (filled, "-fill")):
            found = PATH.findall((MATERIAL/f"{symbol}{suffix}.svg").read_text())
            if len(found) != 1:
                raise SystemExit(f"{symbol}{suffix}.svg: expected a single path, found {len(found)}")
            table[name] = found[0]
    return outline, filled


def generate():
    outline, filled = load_icons()
    # Native shell recolors these at runtime (QML data-URI SVG); no shader effects needed.
    (ROOT/"shell/components/IconData.js").write_text(
        ".pragma library\n// Generated by scripts/generate-design.py from design/icons/material. Do not edit.\n"
        "var outline = "+json.dumps(outline, indent=1)+";\nvar filled = "+json.dumps(filled, indent=1)+";\n")
    preview_icons = {name: f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 -960 960 960" fill="currentColor" aria-hidden="true"><path d="{d}"/></svg>'
                     for name, d in outline.items()}
    (ROOT/"preview/icons.js").write_text("window.PRISM_ICONS = "+json.dumps(preview_icons)+";\n")
    data = {"version": 1, "motion": {"fast":160, "standard":320, "slow":500},
            "shape": {"tileInactive":36, "tileActive":26, "panel":36, "app":24},
            "palettes": {name:{"seed":seed, "light":legacy_tokens(palette(seed)), "dark":legacy_tokens(palette(seed, True))} for name, seed in PALETTES.items()},
            "material": {name:{"light":palette(seed), "dark":palette(seed, True)} for name, seed in PALETTES.items()}}
    (ROOT/"design/tokens.json").write_text(json.dumps(data, indent=2)+"\n")
    # Keep the review preview usable when opened directly through file://.
    (ROOT/"preview/tokens.js").write_text("window.PRISM_TOKENS = "+json.dumps(data)+";\n")
    flower = " ".join(f'{680+math.cos(a)*r:.1f},{350+math.sin(a)*r:.1f}' for i in range(241) for a in [i*math.pi/120] for r in [255+30*math.cos(a*8)])
    wallpaper = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1920 1080">
<rect width="1920" height="1080" fill="#e9dff4"/>
<path d="M0 670Q400 450 760 810T1600 770V1080H0Z" fill="#d2bbe9"/>
<path d="M800 1080Q760 520 1200 500T1920 190V1080Z" fill="#cbe6d7"/>
<ellipse cx="1580" cy="180" rx="330" ry="310" fill="#f7d8ba"/>
<ellipse cx="1580" cy="180" rx="190" ry="180" fill="#e9dff4"/>
<polygon points="{flower}" fill="#bba0dd" transform="translate(270 70) rotate(-12 680 350)"/>
<circle cx="950" cy="420" r="140" fill="#e9dff4"/>
<path d="M1550 820q75-170 175-115t140 180" fill="none" stroke="#8fb9a3" stroke-width="60" stroke-linecap="round"/>
<circle cx="410" cy="950" r="82" fill="#f2cbaa"/>
</svg>\n'''
    (ROOT/"design/wallpaper.svg").write_text(wallpaper)
    (ROOT/"preview/assets/wallpaper.svg").write_text(wallpaper)
    print(f"Generated {len(outline)} Material Symbols icons, wallpaper and shared tokens")


if __name__ == "__main__":
    generate()
